import pandas as pd
import matplotlib.pyplot as plt
## Santiago Medrano NC 0103
df_food_india = pd.read_csv('indian_food.csv')
print("\n--- DATOS LEÍDOS DESDE CSV comida India 0103 ---")
print("Santiago Medrano NC 0103")
print(df_food_india)
print("\n--- Mostrar nombre comida + ingrediantes, comida India 0103 ---")
recipes = df_food_india [['name', 'ingredients']]
print(recipes)
print("\n---tiempo de cocinado mostrar 10 registros con head 0103 ---")
nombre_y_hora = df_food_india[['name', 'cook_time']].head(10)
print(nombre_y_hora)
print("\n---Grafica comida (X) tiempo de cocinado (Y)  0103 ---")
print("\n---Grafica comida (X) texto a 30 grados  0103 ---")
nombre_y_hora.plot.bar(x='name',y='cook_time', rot=30)
plt.title('Comida tipica de India Santiago Medrano 0103')
plt.xlabel('Nombre platillo')
plt.ylabel('tiempo de coccion')
plt.show()
print("\n---gráfica de varias columnas 0103 ---")
name_and_time = df_food_india[['name', 'prep_time', 'cook_time']].head(10)
name_and_time.plot.bar(x='name', rot=30)
plt.title('Grafica de dos columnas Santiago Medrano 0103')
plt.xlabel('Nombre platillo')
plt.ylabel('tiempo de coccion prep comida')
plt.show()
print("\n---Grafdicas apiladas una tras otra verticalmente 0103 ---")
name_and_time.plot.bar(x='name', stacked=True, rot=30)
plt.title('Grafica de 2 columnas apiladas Santiago Medrano 0103')
plt.xlabel('Nombre platillo')
plt.ylabel('tiempo de coccion prep comida')
plt.show()
print(" Santiago Medrano NC 0103")